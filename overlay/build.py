"""Build bin/san14_overlay.dll with llvm-mingw (static runtime, depends only on system DLLs).

The DLL's byte patterns, field offsets and RTTI names come from sigs/sigs.json: every build first writes
overlay/sigs_gen.h from the manifest (the sigs whose "users" list overlay/san14_overlay.cpp).

Usage:
  python -P overlay/build.py                    # write sigs_gen.h, build the DLL
  python -P overlay/build.py --header           # only write sigs_gen.h
  python -P overlay/build.py --check-header     # exit 1 if sigs_gen.h is not what the manifest gives
  python -P overlay/build.py --test [dump_dir]  # also run the DLL's locator (LocateGame) offline against a
                                                # memory dump from tools/dump.py (default: newest in analysis/)
                                                # and compare every address it finds with tools/sigs.py
"""
import glob
import json
import os
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'tools'))
import sigs as S  # noqa: E402

LLVM = os.environ.get('SAN14_LLVM') or r'E:\Tools\extracted\llvm-mingw\llvm-mingw-20261020-ucrt-x86_64\bin'
SRC = os.path.join(ROOT, 'overlay', 'san14_overlay.cpp')
HEADER = os.path.join(ROOT, 'overlay', 'sigs_gen.h')
OUT = os.path.join(ROOT, 'bin', 'san14_overlay.dll')
TEST_SRC = os.path.join(ROOT, 'overlay', 'locate_test.cpp')
TEST_OUT = os.path.join(tempfile.gettempdir(), 'san14_locate_test.exe')
CXX = [os.path.join(LLVM, 'x86_64-w64-mingw32-clang++.exe'), '-O2', '-std=c++17', '-static', '-s', '-Wall',
       '-Wno-unknown-pragmas']
LIBS = ['-ld3d11', '-ldxgi', '-luuid']
DLL_USER = 'overlay/san14_overlay.cpp'
MAX_TOKENS = 256          # Pat in the DLL holds 256 pattern bytes
FIELD_LEN = {'u8': 1, 'u16': 2, 'u32': 4, 'i32': 4}


def run(cmd):
    r = subprocess.run(cmd, capture_output=True, text=True)
    sys.stdout.write(r.stdout + r.stderr)
    return r.returncode


def c_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def gen_header(manifest=None, user=DLL_USER, by='overlay/build.py'):
    """Text of the sigs_gen.h for one DLL: the sigs whose "users" list `user` (also used by aihook/build.py)."""
    m = manifest or S.load()
    out = ['// Generated by %s from sigs/sigs.json. Do not edit: change the manifest and rebuild.' % by,
           '// Every sig the DLL uses: its patterns (one per variant, tried in order), the offsets of its fields',
           '// (same order in every variant) and, for RTTI sigs, the class name and vtable slots.',
           '#pragma once',
           '#include <stdint.h>',
           '',
           'struct SigField { int16_t at; uint8_t len; };',
           'struct SigVariant { const char* pattern; const SigField* fields; };',
           'struct Sig { const char* name; const SigVariant* variants; int nvariants; int count; uint32_t range; };',
           '']
    for name, s in m.sigs.items():
        if user not in s.d.get('users', []):
            continue
        out.append('// %s: %s' % (name, s.desc.replace('\n', ' ')))
        if s.kind == 'rtti':
            out.append('static const char kRtti_%s[] = %s;' % (name, c_str(s.where['rtti'])))
            slots = s.d.get('slots', {})
            if slots:
                out.append('enum { %s };' % ', '.join('SLOT_%s_%s = %d' % (name, k, v) for k, v in slots.items()))
            out.append('')
            continue
        names = list(s.variants[0].fields)
        for v in s.variants:
            if list(v.fields) != names:
                sys.exit('sig %s: variant %d has fields %s, variant 0 has %s (the DLL needs the same fields in the same '
                         'order)' % (name, v.index, list(v.fields), names))
            if len(v.toks) > MAX_TOKENS:
                sys.exit('sig %s: variant %d pattern has %d bytes, the DLL takes at most %d' % (
                    name, v.index, len(v.toks), MAX_TOKENS))
        if names:
            out.append('enum { %s, F_%s_COUNT };' % (', '.join('F_%s_%s' % (name, f) for f in names), name))
        for v in s.variants:
            if names:
                fs = ', '.join('{%d, %d}' % (spec['at'], spec.get('len') or FIELD_LEN.get(spec['kind'], 0))
                               for spec in v.fields.values())
                out.append('static const SigField kF_%s_%d[] = {%s};' % (name, v.index, fs))
        out.append('static const SigVariant kV_%s[] = {%s};' % (name, ', '.join(
            '{%s, %s}' % (c_str(v.pattern), ('kF_%s_%d' % (name, v.index)) if names else 'nullptr') for v in s.variants)))
        out.append('static const Sig SIG_%s = {%s, kV_%s, %d, %d, 0x%x};' % (
            name, c_str(name), name, len(s.variants), s.count, s.where.get('range', 0)))
        for f, spec in s.variants[0].fields.items():
            if 'expect_str' in spec:
                out.append('static const char kStr_%s_%s[] = %s;' % (name, f, c_str(spec['expect_str'])))
        out.append('')
    return '\n'.join(out)


def write_header():
    text = gen_header()
    old = open(HEADER, encoding='utf-8').read() if os.path.exists(HEADER) else None
    if old != text:
        with open(HEADER, 'w', encoding='utf-8', newline='\n') as f:
            f.write(text)
        print('wrote', HEADER)


def header_current():
    return os.path.exists(HEADER) and open(HEADER, encoding='utf-8').read() == gen_header()


def compare_with_manifest(lines, dump_dir):
    """Lines 'sig name[.field] hexvalue' printed by locate_test vs tools/sigs.py on the same dump."""
    res = S.resolve(S.Image.from_dump(dump_dir))
    bad = 0
    for line in lines:
        parts = line.split()
        if len(parts) != 3 or parts[0] != 'sig':
            continue
        ref, got = parts[1], int(parts[2], 16)
        n, _, f = ref.partition('.')
        r = res.get(n)
        want = r.get(f or None) if r and r.ok else None
        if want != got:
            bad += 1
            print('MISMATCH %s: DLL %x, sigs.py %s' % (ref, got, '%x' % want if isinstance(want, int) else want))
    return bad


def test(dump_dir):
    if not dump_dir:
        dumps = sorted(glob.glob(os.path.join(ROOT, 'analysis', 'dump_*')), key=os.path.getmtime)
        if not dumps:
            sys.exit('no dump in analysis/ (make one with tools/dump.py)')
        dump_dir = dumps[-1]
    with open(os.path.join(dump_dir, 'meta.json'), encoding='utf-8') as f:
        base = json.load(f)['runtime_base']
    if run(CXX + ['-o', TEST_OUT, TEST_SRC] + LIBS):
        sys.exit('test build failed')
    print('locate test on', dump_dir)
    r = subprocess.run([TEST_OUT, os.path.join(dump_dir, 'image.bin'), base], capture_output=True, text=True)
    sys.stdout.write(r.stdout + r.stderr)
    if r.returncode:
        sys.exit('locate test FAILED')
    lines = r.stdout.splitlines()
    n = sum(1 for line in lines if line.startswith('sig '))
    bad = compare_with_manifest(lines, dump_dir)
    if bad or not n:
        sys.exit('locate test: %d of %d addresses differ from tools/sigs.py' % (bad, n))
    print('locate test ok: all %d addresses and offsets the DLL found agree with tools/sigs.py' % n)


def main():
    if '--check-header' in sys.argv:
        ok = header_current()
        print('sigs_gen.h is %s' % ('up to date' if ok else 'OUT OF DATE (run python -P overlay/build.py --header)'))
        sys.exit(0 if ok else 1)
    write_header()
    if '--header' in sys.argv:
        return
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    if run(CXX + ['-shared', '-o', OUT, SRC] + LIBS):
        sys.exit('build failed')
    deps = subprocess.run([os.path.join(LLVM, 'llvm-objdump.exe'), '-p', OUT], capture_output=True, text=True).stdout
    print('built', OUT, os.path.getsize(OUT), 'bytes')
    print('imports:', ', '.join(line.split(':', 1)[1].strip() for line in deps.splitlines() if 'DLL Name' in line))
    if '--test' in sys.argv:
        i = sys.argv.index('--test')
        test(sys.argv[i + 1] if len(sys.argv) > i + 1 else None)


if __name__ == '__main__':
    main()
